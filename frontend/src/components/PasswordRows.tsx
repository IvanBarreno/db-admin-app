/** Shown in an empty password box: leaving it empty is a valid choice, not a missing value. */
const EMPTY_HINT = 'generated when the run starts'

/**
 * Editor for a list parameter that comes with ONE PASSWORD PER ITEM (YAML: a password parameter with
 * `generate_for_each: <list>`): one row per login, each with its own password field and its own
 * "Generate…" modal. A password left empty is generated by the API when the run starts.
 *
 * Two shapes, decided by the list parameter:
 *   - the list is TYPED (`typed_list`, e.g. "create several logins"): every row has a name box too, and rows
 *     can be added, removed or pasted in bulk;
 *   - the list comes from a LOOKUP (e.g. "reset passwords"): the logins are ticked in the usual checklist and
 *     a row appears for each ticked one.
 *
 * It writes TWO form values at once: the list (a JSON array of names) and the passwords (a JSON object
 * name → password, typed ones only). See passwordMap.ts.
 */
export function PasswordRows(props: {
  listParam: OperationParameter
  passwordParam: OperationParameter
  values: Record<string, string>
  /** Receives the changed form values (one or both parameters). */
  onChange: (patch: Record<string, string>) => void
  serverName: string | null
  database: string
  allowProtected: boolean
  onBlock: BlockReporter
}) {
  return props.listParam.effectiveSource ? <PickedRows {...props} /> : <TypedRows {...props} />
}

type Props = Parameters<typeof PasswordRows>[0]

/**
 * Asks the API for one password per name, with the DBA's saved generator options. Returns the new passwords;
 * on a failure it shows a toast and returns what it got so far.
 */
function useGenerateMany() {
  const generate = useGeneratePassword()
  const [busy, setBusy] = useState(false)

  async function generateFor(names: readonly string[]): Promise<Record<string, string>> {
    const settings = loadPasswordSettings()
    const made: Record<string, string> = {}
    setBusy(true)
    try {
      // One request per login, one after another: each call returns a NEW random password.
      for (const name of names) made[name] = (await generate.mutateAsync(settings)).password
    } catch (error) {
      notifications.show({ color: 'red', title: 'Could not generate the passwords', message: error instanceof Error ? error.message : String(error) })
    } finally {
      setBusy(false)
    }
    return made
  }

  return { generateFor, busy }
}

// ---------------------------------------------------------------------------------------------------
// Typed list: name + password per row
// ---------------------------------------------------------------------------------------------------

interface Row {
  /** Stable React key: rows are added and removed, so the array index cannot be the key. */
  id: number
  name: string
  password: string
}

// Row ids come from a plain module-level counter: they only have to be unique, and a counter outside the
// component can be used while rendering (a `useRef` may not be read or written during render).
let lastRowId = 0
const newRow = (name = '', password = ''): Row => ({ id: ++lastRowId, name, password })

function TypedRows({ listParam, passwordParam, values, onChange, onBlock }: Props) {

  // The rows live HERE, not in the form values: a row that has no name yet cannot be expressed in a JSON
  // list of names. Every edit is translated to the two form values by `commit`.
  const [rows, setRows] = useState<Row[]>(() => {
    const passwords = parsePasswordMap(values[passwordParam.name])
    const names = parseList(values[listParam.name])
    return names.length > 0 ? names.map((name) => newRow(name, passwords[name] ?? '')) : [newRow()]
  })
  const [pasting, setPasting] = useState(false)
  const { generateFor, busy } = useGenerateMany()

  // The form was cleared from outside (another server or operation): start again with one empty row.
  // (React's "reset state when a prop changes" pattern: compare with the previous prop during render.)
  const listValue = values[listParam.name] ?? ''
  const [previousList, setPreviousList] = useState(listValue)
  if (listValue !== previousList) {
    setPreviousList(listValue)
    if (listValue === '' && rows.some((r) => r.name.trim() !== '')) setRows([newRow()])
  }

  /** Names in row order, trimmed, without blanks; a name written twice counts once (its first row wins). */
  function namesOf(list: readonly Row[]): string[] {
    return [...new Set(list.map((r) => r.name.trim()).filter((name) => name !== ''))]
  }

  function commit(next: Row[]) {
    setRows(next)
    const names = namesOf(next)
    const passwords: Record<string, string> = {}
    for (const row of next) {
      const name = row.name.trim()
      if (name !== '' && row.password !== '' && !(name in passwords)) passwords[name] = row.password
    }
    onChange({ [listParam.name]: encodeList(names), [passwordParam.name]: encodePasswordMap(passwords, names) })
  }

  const update = (id: number, patch: Partial<Row>) => commit(rows.map((r) => (r.id === id ? { ...r, ...patch } : r)))
  const remove = (id: number) => commit(rows.length > 1 ? rows.filter((r) => r.id !== id) : [newRow()])

  /** Second and later rows carrying a name that an earlier row already has. */
  const duplicates = new Set<number>()
  const seen = new Set<string>()
  for (const row of rows) {
    const key = row.name.trim().toLowerCase()
    if (key === '') continue
    if (seen.has(key)) duplicates.add(row.id)
    seen.add(key)
  }

  const names = namesOf(rows)
  const withoutPassword = rows.filter((r) => r.name.trim() !== '' && r.password === '' && !duplicates.has(r.id))

  async function generateAll() {
    const made = await generateFor(withoutPassword.map((r) => r.name.trim()))
    commit(rows.map((r) => (r.password === '' && made[r.name.trim()] ? { ...r, password: made[r.name.trim()] } : r)))
  }

  function addPasted(text: string) {
    const existing = new Set(rows.map((r) => r.name.trim().toLowerCase()))
    const fresh = splitNames(text).filter((name) => !existing.has(name.toLowerCase()))
    // Drop the untouched empty rows so the pasted names do not start under a blank line.
    const kept = rows.filter((r) => r.name.trim() !== '' || r.password !== '')
    commit([...kept, ...fresh.map((name) => newRow(name))])
    setPasting(false)
  }

  // A required list with no name keeps Preview / Execute off, with the reason next to the button.
  const blocking = listParam.required && names.length === 0 ? `Add at least one name in "${fieldLabel(listParam)}".` : null
  useEffect(() => {
    onBlock(listParam.name, blocking)
    return () => onBlock(listParam.name, null)
  }, [onBlock, listParam.name, blocking])

  return (
    <Paper withBorder>
      <RowsHeader label={fieldLabel(listParam)} required={listParam.required ?? false} count={names.length} typedCount={names.length - withoutPassword.length} />
      {listParam.help && (
        <Text size="xs" c="dimmed" px="sm" pt={4}>
          {listParam.help}
        </Text>
      )}

      <Stack gap={6} px="sm" py="xs">
        {rows.map((row, index) => (
          <Group key={row.id} gap="xs" wrap="nowrap" align="flex-start">
            <TextInput
              w={240}
              value={row.name}
              onChange={(e) => update(row.id, { name: e.currentTarget.value })}
              placeholder="login name"
              aria-label={`Login name, row ${index + 1}`}
              error={duplicates.has(row.id) ? 'already in the list' : undefined}
              autoComplete="off"
              data-lpignore="true"
              data-1p-ignore="true"
              spellCheck={false}
              styles={{ input: { fontFamily: 'var(--mantine-font-family-monospace)' } }}
            />
            <div style={{ flex: 1, maxWidth: 420 }}>
              <PasswordField
                compact
                value={row.password}
                onChange={(password) => update(row.id, { password })}
                placeholder={EMPTY_HINT}
                generatorTitle={row.name.trim() ? `Password for [${row.name.trim()}]` : undefined}
                ariaLabel={`Password, row ${index + 1}`}
              />
            </div>
            <Tooltip label="Remove this row">
              <ActionIcon variant="subtle" color="gray" size="lg" onClick={() => remove(row.id)} aria-label={`Remove row ${index + 1}`}>
                <IconTrash size={16} />
              </ActionIcon>
            </Tooltip>
          </Group>
        ))}
      </Stack>

      <RowsFooter
        onGenerateAll={generateAll}
        generateDisabled={withoutPassword.length === 0}
        busy={busy}
        onClear={() => commit(rows.map((r) => ({ ...r, password: '' })))}
        clearDisabled={rows.every((r) => r.password === '')}
      >
        <Button variant="default" size="xs" leftSection={<IconPlus size={14} />} onClick={() => commit([...rows, newRow()])}>
          Add login
        </Button>
        <Button variant="default" size="xs" leftSection={<IconClipboardList size={14} />} onClick={() => setPasting(true)}>
          Paste a list…
        </Button>
      </RowsFooter>

      {pasting && <PasteModal onClose={() => setPasting(false)} onAdd={addPasted} />}
    </Paper>
  )
}

/** Small dialog to paste many names at once (a column from a spreadsheet, a comma-separated line...). */
function PasteModal({ onClose, onAdd }: { onClose: () => void; onAdd: (text: string) => void }) {
  const [text, setText] = useState('')
  const count = splitNames(text).length

  return (
    <Modal opened onClose={onClose} title="Paste a list of login names" centered size="md">
      <Stack gap="sm">
        <Textarea
          value={text}
          onChange={(e) => setText(e.currentTarget.value)}
          autosize
          minRows={6}
          maxRows={14}
          // Put the cursor in the box as soon as the dialog opens: the next action is Ctrl+V.
          data-autofocus
          spellCheck={false}
          placeholder={'one name per line (commas also work)\napp_reports\napp_billing'}
          styles={{ input: { fontFamily: 'var(--mantine-font-family-monospace)', fontSize: 'var(--mantine-font-size-xs)' } }}
        />
        <Text size="xs" c="dimmed">
          Each name becomes a row. Names already in the list are skipped; passwords stay empty until you type or generate them.
        </Text>
        <Group justify="flex-end" gap="xs">
          <Button variant="default" onClick={onClose}>
            Cancel
          </Button>
          <Button onClick={() => onAdd(text)} disabled={count === 0}>
            Add {count} login{count === 1 ? '' : 's'}
          </Button>
        </Group>
      </Stack>
    </Modal>
  )
}

// ---------------------------------------------------------------------------------------------------
// List from a lookup: tick the logins, then one password row per ticked login
// ---------------------------------------------------------------------------------------------------

function PickedRows({ listParam, passwordParam, values, onChange, serverName, database, allowProtected, onBlock }: Props) {
  const picked = parseList(values[listParam.name])
  const passwords = parsePasswordMap(values[passwordParam.name])
  const { generateFor, busy } = useGenerateMany()

  const setPasswords = (next: Record<string, string>, names: readonly string[] = picked) =>
    onChange({ [passwordParam.name]: encodePasswordMap(next, names) })

  const withoutPassword = picked.filter((name) => !passwords[name])

  async function generateAll() {
    setPasswords({ ...passwords, ...(await generateFor(withoutPassword)) })
  }

  return (
    <Stack gap="xs">
      <MultiChecklist
        param={listParam}
        value={values[listParam.name] ?? ''}
        onChange={(list) => {
          // Unticking a login also forgets the password typed for it.
          const names = parseList(list)
          onChange({ [listParam.name]: list, [passwordParam.name]: encodePasswordMap(passwords, names) })
        }}
        serverName={serverName}
        database={database}
        values={values}
        allowProtected={allowProtected}
        onBlock={onBlock}
      />

      {picked.length > 0 && (
        <Paper withBorder>
          <RowsHeader label={fieldLabel(passwordParam)} required={false} count={picked.length} typedCount={picked.length - withoutPassword.length} />
          <Stack gap={6} px="sm" py="xs">
            {picked.map((name) => (
              <Group key={name} gap="xs" wrap="nowrap" align="center">
                <Text size="xs" ff="monospace" w={240} truncate title={name}>
                  {name}
                </Text>
                <div style={{ flex: 1, maxWidth: 420 }}>
                  <PasswordField
                    compact
                    value={passwords[name] ?? ''}
                    onChange={(password) => setPasswords({ ...passwords, [name]: password })}
                    placeholder={EMPTY_HINT}
                    generatorTitle={`Password for [${name}]`}
                    ariaLabel={`New password for ${name}`}
                  />
                </div>
              </Group>
            ))}
          </Stack>
          <RowsFooter
            onGenerateAll={generateAll}
            generateDisabled={withoutPassword.length === 0}
            busy={busy}
            onClear={() => setPasswords({})}
            clearDisabled={Object.keys(passwords).length === 0}
          />
        </Paper>
      )}
    </Stack>
  )
}

// ---------------------------------------------------------------------------------------------------
// Shared header and footer of the rows box
// ---------------------------------------------------------------------------------------------------

function RowsHeader({ label, required, count, typedCount }: { label: string; required: boolean; count: number; typedCount: number }) {
  return (
    <Group gap="sm" px="sm" py={6} wrap="wrap" style={{ borderBottom: '1px solid var(--mantine-color-default-border)' }}>
      <Text size="sm" fw={500}>
        {label}
        {required && (
          <Text span c="red">
            {' '}
            *
          </Text>
        )}
      </Text>
      <Text size="xs" c="dimmed">
        {count} login{count === 1 ? '' : 's'}
        {count > 0 && ` · ${typedCount} with a password set, ${count - typedCount} generated at run time`}
      </Text>
    </Group>
  )
}

function RowsFooter({
  children,
  onGenerateAll,
  generateDisabled,
  busy,
  onClear,
  clearDisabled,
}: {
  children?: React.ReactNode
  onGenerateAll: () => void
  generateDisabled: boolean
  busy: boolean
  onClear: () => void
  clearDisabled: boolean
}) {
  return (
    <Group gap="xs" px="sm" py="xs" wrap="wrap" style={{ borderTop: '1px solid var(--mantine-color-default-border)' }}>
      {children}
      <Tooltip label="Fills every empty password now, with your saved generator options, so you can read and copy them before the run">
        <Button variant="default" size="xs" leftSection={<IconWand size={14} />} onClick={onGenerateAll} disabled={generateDisabled} loading={busy}>
          Generate all
        </Button>
      </Tooltip>
      <Tooltip label="Empties every password box: they are then generated when the run starts">
        <Button variant="subtle" color="gray" size="xs" leftSection={<IconEraser size={14} />} onClick={onClear} disabled={clearDisabled}>
          Clear passwords
        </Button>
      </Tooltip>
    </Group>
  )
}
