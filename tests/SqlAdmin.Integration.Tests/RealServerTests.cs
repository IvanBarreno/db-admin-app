    [ServerFact]
    public async Task Effective_permissions_show_what_roles_really_give_a_user_and_a_login()
    {
        var login = NewLoginName();
        var database = (await Lookup("databases")).Items
            .First(i => string.Equals(i.Extra.GetValueOrDefault("state")?.ToString(), "ONLINE", StringComparison.OrdinalIgnoreCase))
            .Value;
        try
        {
            // A login whose ONLY database access is membership of db_datareader: no explicit grant at all,
            // so "explicit permissions" audits show nothing useful and only the impersonation test tells the truth.
            var setup = await Sql($"""
                CREATE LOGIN [{login}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                CREATE USER [{login}] FOR LOGIN [{login}];
                ALTER ROLE db_datareader ADD MEMBER [{login}];
                """, database);
            Assert.True(setup.Success, setup.Error);

            var inDatabase = await Execute("audit.effective_permissions", new { user_name = login }, database);
            Assert.True(inDatabase.Success, inDatabase.Error);
            var permissions = inDatabase.ResultSets[0].Rows.Select(r => r[4]?.ToString()).ToList(); // permission_name
            Assert.Contains("SELECT", permissions);      // through the role
            Assert.Contains("CONNECT", permissions);
            Assert.DoesNotContain("INSERT", permissions);
            Assert.DoesNotContain("CONTROL", permissions);

            // An object that does not exist is reported clearly instead of an empty grid.
            var missing = await Execute("audit.effective_permissions",
                new { user_name = login, securable = "dbo.zz_it_no_such_table" }, database);
            Assert.False(missing.Success);
            Assert.Contains("does not exist", missing.Error);

            var onServer = await Execute("audit.effective_server_permissions", new { login_name = login });
            Assert.True(onServer.Success, onServer.Error);
            var serverPermissions = onServer.ResultSets[0].Rows.Select(r => r[2]?.ToString()).ToList();
            Assert.Contains("CONNECT SQL", serverPermissions);
            Assert.DoesNotContain("CONTROL SERVER", serverPermissions);
            Assert.Equal("False", Cell(onServer, "is_sysadmin"));

            // The connection was handed back as ourselves: the next call still runs as the app's login.
            Assert.Equal("True", Cell(await Execute("audit.effective_server_permissions",
                new { login_name = await ConnectedLogin() }), "is_sysadmin"));
        }
        finally
        {
            await Sql($"IF DATABASE_PRINCIPAL_ID(N'{login}') IS NOT NULL DROP USER [{login}];", database);
            await DropLoginIfExists(login);
        }
    }

    [ServerFact]
    public async Task Bulk_password_reset_gives_each_login_its_own_working_password_and_logs_none()
    {
        var first = NewLoginName();
        var second = NewLoginName();
        try
        {
            var setup = await Sql($"""
                CREATE LOGIN [{first}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                CREATE LOGIN [{second}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                """);
            Assert.True(setup.Success, setup.Error);
            var values = new { logins = JsonSerializer.Serialize(new[] { first, second }) };

            // Preview: one ALTER LOGIN per login, passwords masked, and a token (the operation is destructive).
            var preview = await Preview("changes.reset_passwords", values);
            Assert.True(preview.Destructive);
            var statements = string.Join("\n", preview.Statements!.Select(s => s.Text));
            Assert.Contains($"ALTER LOGIN [{first}] WITH PASSWORD = '***'", statements);
            Assert.Contains($"ALTER LOGIN [{second}] WITH PASSWORD = '***'", statements);

            var run = await Execute("changes.reset_passwords", values, token: preview.ConfirmToken);
            Assert.True(run.Success, run.Error);
            Assert.Null(run.GeneratedPasswords); // per-item passwords travel in the grid, next to their login

            var grid = run.ResultSets[0];
            Assert.Equal(["login_name", "status", "new_password", "message"], grid.Columns);
            var passwords = grid.Rows.ToDictionary(r => r[0]!.ToString()!, r => r[2]!.ToString()!);
            Assert.All(grid.Rows, r => Assert.Equal("OK", r[1]?.ToString()));
            Assert.NotEqual(passwords[first], passwords[second]);

            // The real proof: each login can connect with ITS password, and not with the other one.
            foreach (var login in new[] { first, second })
            {
                await using var ok = new SqlConnection(ConnectionAs(login, passwords[login]).ConnectionString);
                await ok.OpenAsync();
            }
            await using (var crossed = new SqlConnection(ConnectionAs(first, passwords[second]).ConnectionString))
            {
                await Assert.ThrowsAsync<SqlException>(() => crossed.OpenAsync());
            }

            // Nothing about the passwords in the audit log; the logins themselves are recorded.
            var audit = await _client.GetFromJsonAsync<List<AuditEntryResponse>>(
                $"/api/audit?serverName={Server.Name}&skip=0&take=1", ApiFactory.Json);
            Assert.Contains(first, audit![0].ParametersJson);
            Assert.All(passwords.Values, p =>
            {
                Assert.DoesNotContain(p, audit[0].ParametersJson);
                Assert.DoesNotContain(p, audit[0].Sql);
            });
        }
        finally
        {
            await DropLoginIfExists(first);
            await DropLoginIfExists(second);
        }
    }

