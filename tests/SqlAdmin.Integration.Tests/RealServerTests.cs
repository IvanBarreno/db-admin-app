    // ---- full life cycle of a throwaway login -----------------------------------------------------

    [ServerFact]
    public async Task Login_life_cycle_create_disable_kill_live_session_and_drop()
    {
        var login = NewLoginName();
        try
        {
            // 1. Preview changes nothing: afterwards the login still does not exist.
            var createPreview = await Preview("provisioning.create_sql_login", new { login_name = login });
            Assert.False(createPreview.Destructive);
            Assert.Contains(createPreview.Statements!, s => s.Text.Contains($"CREATE LOGIN [{login}]") && s.Text.Contains("'***'"));
            Assert.Empty((await Execute("audit.login_status", new { login_name = login })).ResultSets[0].Rows);

            // 2. Create with a blank password: the server-side generator fills it and returns it ONCE.
            var created = await Execute("provisioning.create_sql_login", new { login_name = login });
            Assert.True(created.Success, created.Error);
            var password = created.GeneratedPasswords!["password"];
            Assert.True(password.Length >= 12);

            // ...and the audit log never sees it.
            var audit = await _client.GetFromJsonAsync<List<AuditEntryResponse>>(
                $"/api/audit?serverName={Server.Name}&skip=0&take=1", ApiFactory.Json);
            Assert.DoesNotContain(password, audit![0].ParametersJson);
            Assert.DoesNotContain(password, audit[0].Sql);

            // 3. Creating it again is stopped by the preflight check, not by a T-SQL error.
            var again = await Preview("provisioning.create_sql_login", new { login_name = login });
            Assert.Contains(again.Checks!, c => c.Id == "login_exists" && c.Blocking);

            // 4. A LIVE session: connect as the new login with the generated password (which also proves the
            //    password really was set). Pooling is off so this object IS the server session.
            await using var session = new SqlConnection(ConnectionAs(login, password).ConnectionString);
            await session.OpenAsync();
            var spid = session.ServerProcessId.ToString();

            var sessions = await Lookup("sessions", $"?login_name={login}");
            Assert.Contains(sessions.Items, i => i.Value == spid);

            // 5. Disable: destructive for this value, so execute needs the token from the preview.
            var disableValues = new { login_name = login, action = "DISABLE" };
            var refused = await ApiFactory.PostAsync(_client, "/api/operations/changes.set_login_enabled/execute",
                Body(Server.Name, null, disableValues));
            Assert.Equal(HttpStatusCode.PreconditionRequired, refused.StatusCode);

            var disablePreview = await Preview("changes.set_login_enabled", disableValues);
            Assert.True(disablePreview.Destructive);
            Assert.NotNull(disablePreview.ConfirmToken);
            Assert.Contains(disablePreview.Statements!, s => s.Text.Contains($"ALTER LOGIN [{login}] DISABLE"));

            // A token is bound to its exact values: it does not unlock a different request.
            var wrongUse = await ApiFactory.PostAsync(_client, "/api/operations/offboarding.drop_login/execute",
                Body(Server.Name, null, new { login_name = login }, disablePreview.ConfirmToken));
            Assert.Equal(HttpStatusCode.PreconditionRequired, wrongUse.StatusCode);

            var disabled = await Execute("changes.set_login_enabled", disableValues, token: disablePreview.ConfirmToken);
            Assert.True(disabled.Success, disabled.Error);
            var status = await Execute("audit.login_status", new { login_name = login });
            Assert.Equal("True", Cell(status, "is_disabled"));

            // 6. Kill sessions: the dry run names OUR session; a disabled login keeps its open sessions,
            //    which is exactly why the offboarding checklist has this step.
            var killValues = new { login_name = login };
            var killPreview = await Preview("offboarding.kill_sessions", killValues);
            Assert.Contains(killPreview.Statements!, s => s.Text.Contains($"KILL {spid}"));

            var killed = await Execute("offboarding.kill_sessions", killValues, token: killPreview.ConfirmToken);
            Assert.True(killed.Success, killed.Error);
            Assert.Equal("0", Cell(killed, "sessions_remaining"));

            // The client side notices on its next command: the server closed the connection.
            await using (var command = session.CreateCommand())
            {
                command.CommandText = "SELECT 1;";
                await Assert.ThrowsAnyAsync<Exception>(() => command.ExecuteScalarAsync());
            }

            // 7. Drop: token again, and afterwards the login is gone.
            var dropPreview = await Preview("offboarding.drop_login", new { login_name = login });
            Assert.Contains(dropPreview.Statements!, s => s.Text.Contains($"DROP LOGIN [{login}]"));
            var dropped = await Execute("offboarding.drop_login", new { login_name = login }, token: dropPreview.ConfirmToken);
            Assert.True(dropped.Success, dropped.Error);
            Assert.Empty((await Execute("audit.login_status", new { login_name = login })).ResultSets[0].Rows);
        }
        finally
        {
            await DropLoginIfExists(login);
        }
    }
