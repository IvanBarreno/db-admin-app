    [ServerFact]
    public async Task Object_permissions_grant_what_fits_skip_what_does_not_and_can_be_revoked()
    {
        var login = NewLoginName();
        var table = "zz_it_t_" + Guid.NewGuid().ToString("N")[..8];
        var procedure = "zz_it_p_" + Guid.NewGuid().ToString("N")[..8];
        var database = (await Lookup("databases")).Items
            .First(i => string.Equals(i.Extra.GetValueOrDefault("state")?.ToString(), "ONLINE", StringComparison.OrdinalIgnoreCase))
            .Value;
        try
        {
            // A user with no rights at all, one table and one procedure. (GO: CREATE PROCEDURE must start a batch.)
            var setup = await Sql($"""
                CREATE LOGIN [{login}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                CREATE USER [{login}] FOR LOGIN [{login}];
                CREATE TABLE dbo.[{table}] (id int);
                GO
                CREATE PROCEDURE dbo.[{procedure}] AS SELECT 1;
                """, database);
            Assert.True(setup.Success, setup.Error);

            var grant = new
            {
                user_name = login,
                action = "GRANT",
                permissions = JsonSerializer.Serialize(new[] { "SELECT", "EXECUTE" }),
                objects = JsonSerializer.Serialize(new[] { $"dbo.{table}", $"dbo.{procedure}" }),
            };

            // Preview: exactly the two statements that make sense; the two that do not are not offered.
            var preview = await Preview("changes.object_permissions", grant, database);
            var statements = preview.Statements!.Select(s => s.Text).ToList();
            Assert.Contains(statements, s => s.Contains($"GRANT SELECT ON OBJECT::[dbo].[{table}] TO [{login}]"));
            Assert.Contains(statements, s => s.Contains($"GRANT EXECUTE ON OBJECT::[dbo].[{procedure}] TO [{login}]"));
            Assert.DoesNotContain(statements, s => s.Contains($"EXECUTE ON OBJECT::[dbo].[{table}]"));
            Assert.Null(preview.ConfirmToken); // GRANT only adds: no confirmation

            var granted = await Execute("changes.object_permissions", grant, database);
            Assert.True(granted.Success, granted.Error);
            string Status(string target, string permission) => granted.ResultSets[0].Rows
                .Single(r => r[0]?.ToString() == target && r[1]?.ToString() == permission)[2]!.ToString()!;
            Assert.Equal("OK", Status($"dbo.{table}", "SELECT"));
            Assert.Equal("OK", Status($"dbo.{procedure}", "EXECUTE"));
            Assert.Equal("SKIPPED", Status($"dbo.{table}", "EXECUTE"));    // EXECUTE does not apply to a table
            Assert.Equal("SKIPPED", Status($"dbo.{procedure}", "SELECT")); // SELECT does not apply to a procedure

            // The engine agrees: impersonating the user, SELECT is now effective on the table.
            var effective = await Execute("audit.effective_permissions", new { user_name = login, securable = $"dbo.{table}" }, database);
            Assert.Contains("SELECT", effective.ResultSets[0].Rows.Select(r => r[4]?.ToString()));

            // A schema-level grant covers every object of the schema.
            var onSchema = await Execute("changes.object_permissions", new
            {
                user_name = login, action = "GRANT",
                permissions = JsonSerializer.Serialize(new[] { "INSERT" }),
                schemas = JsonSerializer.Serialize(new[] { "dbo" }),
            }, database);
            Assert.True(onSchema.Success, onSchema.Error);
            effective = await Execute("audit.effective_permissions", new { user_name = login, securable = $"dbo.{table}" }, database);
            Assert.Contains("INSERT", effective.ResultSets[0].Rows.Select(r => r[4]?.ToString()));

            // REVOKE takes rights away, so it needs the confirm token; afterwards SELECT is gone.
            var revoke = new
            {
                user_name = login, action = "REVOKE",
                permissions = JsonSerializer.Serialize(new[] { "SELECT" }),
                objects = JsonSerializer.Serialize(new[] { $"dbo.{table}" }),
            };
            var revokePreview = await Preview("changes.object_permissions", revoke, database);
            Assert.NotNull(revokePreview.ConfirmToken);
            Assert.Contains(revokePreview.Statements!, s => s.Text.Contains($"REVOKE SELECT ON OBJECT::[dbo].[{table}] FROM [{login}]"));
            var revoked = await Execute("changes.object_permissions", revoke, database, revokePreview.ConfirmToken);
            Assert.True(revoked.Success, revoked.Error);
            effective = await Execute("audit.effective_permissions", new { user_name = login, securable = $"dbo.{table}" }, database);
            Assert.DoesNotContain("SELECT", effective.ResultSets[0].Rows.Select(r => r[4]?.ToString()));

            // Nothing ticked is refused before anything runs.
            var nothing = await Preview("changes.object_permissions",
                new { user_name = login, action = "GRANT", permissions = JsonSerializer.Serialize(new[] { "SELECT" }) }, database);
            Assert.Contains(nothing.Checks!, c => c.Id == "dry_run" && c.Blocking && c.Message.Contains("at least one"));
        }
        finally
        {
            await Sql($"""
                IF OBJECT_ID(N'dbo.[{procedure}]') IS NOT NULL DROP PROCEDURE dbo.[{procedure}];
                IF OBJECT_ID(N'dbo.[{table}]') IS NOT NULL DROP TABLE dbo.[{table}];
                IF DATABASE_PRINCIPAL_ID(N'{login}') IS NOT NULL DROP USER [{login}];
                """, database);
            await DropLoginIfExists(login);
        }
    }

    [ServerFact]
    public async Task Clone_database_access_copies_roles_and_permissions_and_is_idempotent()
    {
        var source = NewLoginName();
        var target = NewLoginName();
        var table = "zz_it_t_" + Guid.NewGuid().ToString("N")[..8];
        var database = (await Lookup("databases")).Items
            .First(i => string.Equals(i.Extra.GetValueOrDefault("state")?.ToString(), "ONLINE", StringComparison.OrdinalIgnoreCase))
            .Value;
        try
        {
            // Source: one role, a database-level grant, an object grant, a column-level DENY and a schema grant.
            var setup = await Sql($"""
                CREATE LOGIN [{source}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                CREATE LOGIN [{target}] WITH PASSWORD = N'Zz!{Guid.NewGuid():N}', CHECK_POLICY = OFF;
                CREATE USER [{source}] FOR LOGIN [{source}];
                CREATE USER [{target}] FOR LOGIN [{target}];
                CREATE TABLE dbo.[{table}] (id int, secret int);
                ALTER ROLE db_datareader ADD MEMBER [{source}];
                GRANT VIEW DEFINITION TO [{source}];
                GRANT INSERT ON OBJECT::dbo.[{table}] TO [{source}];
                DENY SELECT ON OBJECT::dbo.[{table}] (secret) TO [{source}];
                GRANT EXECUTE ON SCHEMA::dbo TO [{source}];
                """, database);
            Assert.True(setup.Success, setup.Error);
            var values = new { source_user = source, target_user = target };

            // The comparison lookup lists what the source holds; the target starts with nothing.
            var held = (await Lookup("database_access", $"?database={database}&user_name={source}")).Items.Select(i => i.Value).ToList();
            Assert.Contains("ROLE:db_datareader", held);
            Assert.Contains($"PERMISSION:SELECT ON dbo.{table} (secret)", held);
            Assert.Empty((await Lookup("database_access", $"?database={database}&user_name={target}")).Items);

            var preview = await Preview("changes.clone_database_access", values, database);
            var statements = string.Join("\n", preview.Statements!.Select(s => s.Text));
            Assert.Contains($"ALTER ROLE [db_datareader] ADD MEMBER [{target}];", statements);
            Assert.Contains($"GRANT VIEW DEFINITION TO [{target}];", statements);
            Assert.Contains($"GRANT INSERT ON OBJECT::[dbo].[{table}] TO [{target}];", statements);
            Assert.Contains($"DENY SELECT ON OBJECT::[dbo].[{table}] ([secret]) TO [{target}];", statements);
            Assert.Contains($"GRANT EXECUTE ON SCHEMA::[dbo] TO [{target}];", statements);
            Assert.DoesNotContain("GRANT CONNECT", statements); // a user always has it

            var run = await Execute("changes.clone_database_access", values, database);
            Assert.True(run.Success, run.Error);
            Assert.All(run.ResultSets[0].Rows, r => Assert.Equal("OK", r[2]?.ToString()));

            // Afterwards both users hold the same things...
            var after = (await Lookup("database_access", $"?database={database}&user_name={target}")).Items.Select(i => i.Value).Order().ToList();
            Assert.Equal(held.Order(), after);

            // ...and running it again finds nothing left to copy.
            var again = await Preview("changes.clone_database_access", values, database);
            Assert.Empty(again.Statements!);

            // Same user twice is refused by the preflight check.
            var same = await Preview("changes.clone_database_access", new { source_user = source, target_user = source }, database);
            Assert.Contains(same.Checks!, c => c.Id == "different_users" && c.Blocking);
        }
        finally
        {
            await Sql($"""
                IF OBJECT_ID(N'dbo.[{table}]') IS NOT NULL DROP TABLE dbo.[{table}];
                IF DATABASE_PRINCIPAL_ID(N'{source}') IS NOT NULL DROP USER [{source}];
                IF DATABASE_PRINCIPAL_ID(N'{target}') IS NOT NULL DROP USER [{target}];
                """, database);
            await DropLoginIfExists(source);
            await DropLoginIfExists(target);
        }
    }

    [ServerFact]
    public async Task Typed_and_generated_passwords_can_be_mixed_and_only_generated_ones_are_shown()
    {
        var typedLogin = NewLoginName();
        var generatedLogin = NewLoginName();
        // Quotes and a backslash on purpose: the password travels inside JSON and then inside a T-SQL literal.
        var typedPassword = "Typed'\"\\#" + Guid.NewGuid().ToString("N")[..12] + "aA1";
        try
        {
            var values = new
            {
                login_names = JsonSerializer.Serialize(new[] { typedLogin, generatedLogin }),
                // Only the typed one is sent; the other login is absent = "generate it".
                passwords = JsonSerializer.Serialize(new Dictionary<string, string> { [typedLogin] = typedPassword }),
            };

            // The preview masks every password, typed or not.
            var preview = await Preview("provisioning.create_sql_logins", values);
            var statements = string.Join("\n", preview.Statements!.Select(s => s.Text));
            Assert.Contains($"CREATE LOGIN [{typedLogin}] WITH PASSWORD = '***'", statements);
            Assert.DoesNotContain(typedPassword, statements);

            var run = await Execute("provisioning.create_sql_logins", values);
            Assert.True(run.Success, run.Error);
            var rows = run.ResultSets[0].Rows.ToDictionary(r => r[0]!.ToString()!, r => r);

            // Typed: kept as typed and NOT echoed back. Generated: shown once.
            Assert.Equal("(as typed)", rows[typedLogin][2]?.ToString());
            var generatedPassword = rows[generatedLogin][2]!.ToString()!;
            Assert.True(generatedPassword.Length >= 12);
            Assert.NotEqual("(as typed)", generatedPassword);

            // Both really work.
            await using (var a = new SqlConnection(ConnectionAs(typedLogin, typedPassword).ConnectionString)) await a.OpenAsync();
            await using (var b = new SqlConnection(ConnectionAs(generatedLogin, generatedPassword).ConnectionString)) await b.OpenAsync();

            // Neither password reaches the audit log.
            var audit = await _client.GetFromJsonAsync<List<AuditEntryResponse>>(
                $"/api/audit?serverName={Server.Name}&skip=0&take=1", ApiFactory.Json);
            Assert.DoesNotContain(typedPassword, audit![0].ParametersJson);
            Assert.DoesNotContain(generatedPassword, audit[0].ParametersJson);

            // Reset with a typed password for one of them: the token from the preview covers the typed value.
            var newPassword = "Reset#" + Guid.NewGuid().ToString("N")[..14] + "aA1";
            var reset = new
            {
                logins = JsonSerializer.Serialize(new[] { typedLogin, generatedLogin }),
                passwords = JsonSerializer.Serialize(new Dictionary<string, string> { [generatedLogin] = newPassword }),
            };
            var resetPreview = await Preview("changes.reset_passwords", reset);
            var resetRun = await Execute("changes.reset_passwords", reset, token: resetPreview.ConfirmToken);
            Assert.True(resetRun.Success, resetRun.Error);
            var resetRows = resetRun.ResultSets[0].Rows.ToDictionary(r => r[0]!.ToString()!, r => r);
            Assert.Equal("(as typed)", resetRows[generatedLogin][2]?.ToString());
            await using (var c = new SqlConnection(ConnectionAs(generatedLogin, newPassword).ConnectionString)) await c.OpenAsync();
            await using (var d = new SqlConnection(ConnectionAs(typedLogin, resetRows[typedLogin][2]!.ToString()!).ConnectionString)) await d.OpenAsync();

            // A password that is too long is refused at preview, naming the login and not the value.
            var tooLong = new string('x', 129);
            var refused = await ApiFactory.PostAsync(_client, "/api/operations/changes.reset_passwords/preview", Body(Server.Name, null, new
            {
                logins = JsonSerializer.Serialize(new[] { typedLogin }),
                passwords = JsonSerializer.Serialize(new Dictionary<string, string> { [typedLogin] = tooLong }),
            }));
            Assert.Equal(HttpStatusCode.BadRequest, refused.StatusCode);
            var body = await refused.Content.ReadAsStringAsync();
            Assert.Contains(typedLogin, body);
            Assert.DoesNotContain(tooLong, body);
        }
        finally
        {
            await DropLoginIfExists(typedLogin);
            await DropLoginIfExists(generatedLogin);
        }
    }

