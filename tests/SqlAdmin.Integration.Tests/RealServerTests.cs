    private readonly HttpClient _client = factory.CreateClient();

    /// <summary>The lab server, checked once per test: it must be configured and must not be Production.</summary>
    private ServerDefinition Server
    {
        get
        {
            var name = ServerFactAttribute.ServerName!;
            var server = factory.Servers.Find(name)
                         ?? throw new InvalidOperationException($"{ServerFactAttribute.Variable}='{name}' is not in servers.json.");
            if (server.IsProduction)
                throw new InvalidOperationException($"'{name}' is a Production server: integration tests refuse to run there.");
            return server;
        }
    }

    // ---- small helpers: one line per API call in the tests below -------------------------------

    private static object Body(string server, string? database, object parameters, string? token = null) =>
        new { serverName = server, database, @params = parameters, confirmToken = token };

    private async Task<OperationPreviewResult> Preview(string operationId, object parameters, string? database = null)
    {
        var response = await ApiFactory.PostAsync(_client, $"/api/operations/{operationId}/preview", Body(Server.Name, database, parameters));
        Assert.True(response.IsSuccessStatusCode, await response.Content.ReadAsStringAsync());
        return (await response.Content.ReadFromJsonAsync<OperationPreviewResult>(ApiFactory.Json))!;
    }

    private async Task<OperationExecuteResult> Execute(string operationId, object parameters, string? database = null, string? token = null)
    {
        var response = await ApiFactory.PostAsync(_client, $"/api/operations/{operationId}/execute", Body(Server.Name, database, parameters, token));
        Assert.True(response.IsSuccessStatusCode, await response.Content.ReadAsStringAsync());
        return (await response.Content.ReadFromJsonAsync<OperationExecuteResult>(ApiFactory.Json))!;
    }

    private async Task<CustomSqlResult> Sql(string sql, string? database = null)
    {
        var response = await ApiFactory.PostAsync(_client, "/api/custom-sql", new { serverName = Server.Name, database, sql });
        Assert.True(response.IsSuccessStatusCode, await response.Content.ReadAsStringAsync());
        return (await response.Content.ReadFromJsonAsync<CustomSqlResult>(ApiFactory.Json))!;
    }

    private async Task<LookupResult> Lookup(string id, string query = "")
    {
        var result = await _client.GetFromJsonAsync<LookupResult>($"/api/servers/{Server.Name}/lookups/{id}{query}", ApiFactory.Json);
        return result!;
    }

    /// <summary>Cell of the first result set by column name. JSON numbers / strings arrive as JsonElement.</summary>
    private static string? Cell(OperationExecuteResult result, string column, int row = 0)
    {
        var set = result.ResultSets[0];
        var index = set.Columns.ToList().IndexOf(column);
        Assert.True(index >= 0, $"column '{column}' not in [{string.Join(", ", set.Columns)}]");
        return set.Rows[row][index]?.ToString();
    }

    private async Task<string> ConnectedLogin()
    {
        var response = await _client.PostAsync($"/api/servers/{Server.Name}/test", null);
        var test = await response.Content.ReadFromJsonAsync<JsonElement>(ApiFactory.Json);
        Assert.True(test.GetProperty("success").GetBoolean(), test.GetProperty("error").ToString());
        return test.GetProperty("info").GetProperty("loginName").GetString()!;
    }

    private static string NewLoginName() => "zz_it_" + Guid.NewGuid().ToString("N")[..12];

    /// <summary>Best-effort clean-up: kill the login's sessions, then drop it. Never throws.</summary>
    private async Task DropLoginIfExists(string login)
    {
        // The name is generated by NewLoginName (letters and digits only), so embedding it is safe here.
        await Sql($"""
            DECLARE @kill nvarchar(max) = N'';
            SELECT @kill += N'KILL ' + CAST(session_id AS nvarchar(10)) + N';'
            FROM sys.dm_exec_sessions WHERE login_name = N'{login}' AND session_id <> @@SPID;
            EXEC (@kill);
            IF SUSER_ID(N'{login}') IS NOT NULL DROP LOGIN [{login}];
            """);
    }

